export function getArticleBySlug(slug) {
  return articles.find((a) => a.slug === slug);
}

export function getLeadArticle() {
  return articles.find((a) => a.isLead) ?? articles[0];
}

export function getSecondaryArticles() {
  return articles.filter((a) => !a.isLead).slice(0, 4);
}

export function getRelated(slug, limit = 3) {
  const current = getArticleBySlug(slug);
  if (!current) return articles.slice(0, limit);
  return articles
    .filter((a) => a.slug !== slug && a.category.en === current.category.en)
    .concat(articles.filter((a) => a.slug !== slug && a.category.en !== current.category.en))
    .slice(0, limit);
}
